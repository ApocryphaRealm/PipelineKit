r"""Generate (or check) gate-rules-INDEX.md: the gate rules by kind and by mod.

USAGE
    py -3 gate-rules-index.py [--rules <path>] (--build | --check)

--rules defaults to gate-rules.json beside this script; the index is written beside the rules file as
gate-rules-INDEX.md. --check prints STALE / NO INDEX (exit 1) or OK <n> rules (exit 0); the first two lines
(title and stamp with the date) are ignored. Read-only on the rules file.
"""
import datetime, io, os, sys, json

HERE = os.path.dirname(os.path.abspath(__file__))
FIX_MAX = 120


def read_text(path):
    data = open(path, "rb").read()
    if data.startswith(b"\xef\xbb\xbf"):
        data = data[3:]
    return data.decode("utf-8", errors="replace").replace("\r\n", "\n").replace("\r", "\n")


def esc(s):
    return str(s).replace("\n", " ").replace("|", "\\|")


def as_list(v):
    if v is None:
        return []
    if isinstance(v, (list, tuple)):
        return [str(x) for x in v]
    return [str(v)]


def applies_to(rule):
    mods = as_list(rule.get("mods"))
    exempt = as_list(rule.get("exemptMods"))
    if mods:
        s = "only: " + ", ".join(mods)
    elif exempt:
        s = "all except: " + ", ".join(exempt)
    else:
        s = "all mods"
    kinds = as_list(rule.get("kinds"))
    if kinds:
        s += "; kinds: " + ", ".join(kinds)
    return s


def fix_of(rule):
    f = rule.get("fix")
    if not isinstance(f, str) or not f.strip():
        return "-"
    f = " ".join(f.split())
    return f[:FIX_MAX]


def build_text(rules, today):
    by_kind = {}
    for r in rules:
        by_kind.setdefault(str(r.get("kind", "?")), []).append(r)
    kinds_sorted = sorted(by_kind, key=lambda k: (-len(by_kind[k]), k))
    out = ["# Gate rules index (GENERATED by gate-rules-index.py --build, do not edit by hand)",
           "<!-- GENERATED %s by gate-rules-index.py from %d rules of %d kinds -->" % (today, len(rules), len(kinds_sorted)),
           "",
           "package-gate.ps1 evaluates every rule in gate-rules.json against a package. Grep here by kind, by mod, by the",
           "rule's id or by a word of its `why`; the row's `added` date says when the defect class was found.",
           "",
           "## By kind"]
    for k in kinds_sorted:
        out += ["", "### %s (%d)" % (k, len(by_kind[k])), "", "| id | added | applies to | fix |", "|---|---|---|---|"]
        for r in by_kind[k]:
            out.append("| %s | %s | %s | %s |" % (esc(r.get("id", "?")), esc(r.get("added") or "-"),
                                                  esc(applies_to(r)), esc(fix_of(r))))
    mods = {}
    for r in rules:
        for m in as_list(r.get("mods")):
            mods.setdefault(m, []).append("%s (only)" % r.get("id", "?"))
        for m in as_list(r.get("exemptMods")):
            mods.setdefault(m, []).append("%s (exempt)" % r.get("id", "?"))
    out += ["", "## By mod"]
    for m in sorted(mods, key=lambda s: (s.lower(), s)):
        out += ["", "### %s" % m, ""]
        out += ["- " + x for x in mods[m]]
    scripts = {}
    for r in rules:
        s = r.get("script")
        if isinstance(s, str) and s.strip():
            scripts.setdefault(s, []).append(str(r.get("id", "?")))
    out += ["", "## Scripts the rules run", ""]
    for s in sorted(scripts):
        out.append("- `%s`: %s" % (s, ", ".join(scripts[s])))
    return "\n".join(out) + "\n"


def main(argv):
    rules_path, mode = os.path.join(HERE, "gate-rules.json"), None
    i = 0
    while i < len(argv):
        if argv[i] == "--rules" and i + 1 < len(argv):
            rules_path = argv[i + 1]; i += 2
        elif argv[i] in ("--build", "--check"):
            mode = argv[i]; i += 1
        else:
            mode = None; break
    if not mode:
        print("usage: gate-rules-index.py [--rules <path>] (--build | --check)")
        return 2
    rules = json.loads(read_text(rules_path)).get("rules", [])
    idx_path = os.path.join(os.path.dirname(os.path.abspath(rules_path)), "gate-rules-INDEX.md")
    today = datetime.date.today().isoformat()
    text = build_text(rules, today)
    if mode == "--build":
        with io.open(idx_path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("BUILT %d rules" % len(rules))
        # the gate catalogue (role gate-catalogue, 2026-10-27) is rebuilt with the index of the REAL rules file
        if os.path.normcase(os.path.abspath(rules_path)) == os.path.normcase(os.path.join(HERE, "gate-rules.json")):
            import subprocess
            r = subprocess.run([sys.executable, os.path.join(HERE, "gate-catalogue.py"), "--build"],
                               capture_output=True, text=True, encoding="utf-8", errors="replace")
            print((r.stdout.strip() or r.stderr.strip() or "gate-catalogue: no output").splitlines()[-1])
        return 0
    if not os.path.exists(idx_path):
        print("NO INDEX")
        return 1
    if text.split("\n")[2:] != read_text(idx_path).split("\n")[2:]:
        print("STALE")
        return 1
    print("OK %d rules" % len(rules))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
