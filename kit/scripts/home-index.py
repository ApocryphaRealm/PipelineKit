r"""Generate (or check) INDEX.md for a folder of documents.

USAGE
    py -3 home-index.py --dir <folder> (--build | --check) [--title "<text>"]

Reads every *.md and *.txt in the folder except INDEX.md, non-recursively. Per file:
  date     the first yyyy-mm-dd in the file name, else in the first 20 lines, else the last-modified date
  heading  the first line starting "# " (outside code fences), else the first non-empty line, max 100 chars
  topics   a frontmatter `topics:` list, else a `<!-- topics: a, b -->` comment in the first 20 lines, else "-"
--check prints STALE INDEX.md / NO INDEX.md (exit 1) or OK <n> files indexed (exit 0); the stamp's date
and the title line are ignored.
"""
import datetime, io, os, re, sys

SKIP = ("INDEX.md",)
DATE_RE = re.compile(r"\d{4}-\d{2}-\d{2}")
SCRIPT_PATH = "D:" + chr(92) + "Claude output" + chr(92) + ".MD" + chr(92) + "scripts" + chr(92) + "home-index.py"


def read_text(path):
    data = open(path, "rb").read()
    if data.startswith(b"\xef\xbb\xbf"):
        data = data[3:]
    return data.decode("utf-8", errors="replace").replace("\r\n", "\n").replace("\r", "\n")


def valid_date(s):
    try:
        datetime.date.fromisoformat(s)
        return True
    except ValueError:
        return False


def first_date(text):
    for m in DATE_RE.finditer(text):
        if valid_date(m.group(0)):
            return m.group(0)
    return None


def split_frontmatter(lines):
    """-> (frontmatter lines or None, index of first body line)"""
    if lines and lines[0].strip() == "---":
        for i in range(1, len(lines)):
            if lines[i].strip() == "---":
                return lines[1:i], i + 1
    return None, 0


def fm_topics(fm):
    for i, line in enumerate(fm):
        m = re.match(r"^\s*topics:\s*(.*)$", line)
        if not m:
            continue
        val = m.group(1).strip()
        if val.startswith("["):
            inner = val[1:val.rfind("]")] if "]" in val else val[1:]
            return [t.strip().strip("\"'") for t in inner.split(",") if t.strip()]
        if val == "":
            items = []
            for j in range(i + 1, len(fm)):
                mm = re.match(r"^\s*-\s*(.+?)\s*$", fm[j])
                if mm:
                    items.append(mm.group(1).strip("\"'"))
                elif fm[j].strip():
                    break
            return items
        return [t.strip().strip("\"'") for t in val.split(",") if t.strip()]
    return None


def heading_of(lines, start):
    fence = False
    for line in lines[start:]:
        if line.lstrip().startswith("```"):
            fence = not fence
            continue
        if not fence and line.startswith("# "):
            return line[2:].strip()[:100]
    for line in lines[start:]:
        if line.strip():
            return line.strip()[:100]
    return "-"


def describe(folder, fn):
    path = os.path.join(folder, fn)
    text = read_text(path)
    lines = text.split("\n")
    fm, start = split_frontmatter(lines)
    head20 = "\n".join(lines[:20])
    date = first_date(fn) or first_date(head20)
    if not date:
        date = datetime.date.fromtimestamp(os.path.getmtime(path)).isoformat()
    topics = fm_topics(fm) if fm is not None else None
    if not topics:
        m = re.search(r"<!--\s*topics:\s*(.*?)\s*-->", head20)
        topics = [t.strip() for t in m.group(1).split(",") if t.strip()] if m else []
    return {"file": fn, "date": date, "heading": heading_of(lines, start), "topics": topics}


def load(folder):
    items = []
    for fn in os.listdir(folder):
        full = os.path.join(folder, fn)
        if not os.path.isfile(full) or fn in SKIP or not fn.lower().endswith((".md", ".txt")):
            continue
        items.append(describe(folder, fn))
    items.sort(key=lambda d: (tuple(-ord(c) for c in d["date"]), d["file"]))
    return items


def esc(s):
    return s.replace("\n", " ").replace("|", "\\|")


def build_text(folder, items, title, today):
    if not title:
        title = "Index of " + os.path.basename(os.path.normpath(folder))
    out = ["# %s (GENERATED by home-index.py --build, do not edit by hand)" % title,
           "<!-- GENERATED %s by home-index.py from %d files -->" % (today, len(items)), "",
           "Grep this file for a date, a word of a heading or a topic; open the file it names. A file in this folder that is",
           'not listed here is new since the last build: run `py -3 "%s" --dir "%s" --build`.' % (SCRIPT_PATH, folder), "",
           "| date | file | heading | topics |", "|---|---|---|---|"]
    for d in items:
        out.append("| %s | [%s](%s) | %s | %s |" % (d["date"], d["file"], d["file"], esc(d["heading"]),
                                                     ", ".join(d["topics"]) if d["topics"] else "-"))
    return "\n".join(out) + "\n"


def body_without_title_and_stamp(text):
    lines = text.replace("\r\n", "\n").split("\n")
    return lines[2:]


def main(argv):
    folder, mode, title = None, None, None
    i = 0
    while i < len(argv):
        if argv[i] == "--dir" and i + 1 < len(argv):
            folder = argv[i + 1]; i += 2
        elif argv[i] == "--title" and i + 1 < len(argv):
            title = argv[i + 1]; i += 2
        elif argv[i] in ("--build", "--check"):
            mode = argv[i]; i += 1
        else:
            mode = None; folder = None; break
    if not folder or not mode:
        print('usage: home-index.py --dir <folder> (--build | --check) [--title "<text>"]')
        return 2
    items = load(folder)
    today = datetime.date.today().isoformat()
    idx_path = os.path.join(folder, "INDEX.md")
    if mode == "--build":
        with io.open(idx_path, "w", encoding="utf-8", newline="\n") as f:
            f.write(build_text(folder, items, title, today))
        print("BUILT %d files" % len(items))
        return 0
    if not os.path.exists(idx_path):
        print("NO INDEX.md")
        return 1
    want = body_without_title_and_stamp(build_text(folder, items, title, today))
    have = body_without_title_and_stamp(read_text(idx_path))
    if want != have:
        print("STALE INDEX.md")
        return 1
    print("OK %d files indexed" % len(items))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
