r"""gate-catalogue.py (role gate-catalogue) - one generated page of every gate: where it runs, what calls it, when it last
fired (2026-10-27, pipeline assessment item 11).

The gates sat mostly at FINALIZE while the day's damage happened at package, install, test and brief time. This page
makes that visible: for every gate-rules.json row the stage it runs at, the tool that calls it and the last date the
event log shows it refusing something; for every standalone gate script in the gates folder, its first doc line and the
tools that call it. Rows that have never fired, or that fire only at finalize, are listed as candidates to move earlier
or retire - a look, not a verdict.

    py -3 gate-catalogue.py --build [--rules F] [--events F] [--out F]   write GATE-CATALOGUE.md beside gate-rules.json
    py -3 gate-catalogue.py --check [...]                                 exit 1 when the page is missing or stale

"Fired" = a gate event (kind gate, outcome fail) whose reasons name the row ('gate-rules:<id>' or '[<id>]').
Stage: package-gate.ps1 evaluates every row at PACKAGE (package-mod, repack-fomod) and at FINALIZE (pre-finalize-check,
inside finalize-mod), and gate-sweep runs it over every posted mod; rows that read the Nexus distro folder, the mod page
or the previous release can only hit when those are given - at finalize. The first two lines (title, stamp) are ignored
by --check. Read-only on everything but the page.
"""
import argparse, datetime, io, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
MD = os.path.dirname(HERE)
FINALIZE_ONLY_KINDS = re.compile(r"^(page-|distro-|keep-file-classes-of-previous|fomod-delivers-previous-files|"
                                 r"archive-matches-folder|changelog-top-version|mo2-install-matches-package)")
PACKAGE_GATE_CALLERS = "package-mod, repack-fomod, pre-finalize-check (finalize-mod), gate-sweep"


def read_text(path):
    with open(path, "rb") as f:
        data = f.read()
    return data.decode("utf-8-sig", errors="replace").replace("\r\n", "\n")


def last_fired(events_path):
    """row id -> (last date, count) from the event log's failing gate events."""
    out = {}
    if not events_path or not os.path.isfile(events_path):
        return out
    with open(events_path, encoding="utf-8", errors="replace") as f:
        for line in f:
            if '"gate' not in line:
                continue
            try:
                e = json.loads(line)
            except ValueError:
                continue
            if e.get("kind") != "gate" and not str(e.get("event", "")).lower().startswith("gate-fail"):
                continue
            if e.get("outcome") not in (None, "fail") or "pass" in str(e.get("event", "")).lower():
                continue
            ids = set()
            for r in e.get("reasons") or []:
                ids.update(re.findall(r"gate-rules:([A-Za-z0-9_.-]+)", str(r)))
                ids.update(re.findall(r"\[([a-z0-9][a-z0-9-]+)\]", str(r)))
            ids.update(re.findall(r"gate-rules:([A-Za-z0-9_.-]+)", str(e.get("note") or "")))
            day = str(e.get("ts", ""))[:10]
            for i in ids:
                d, n = out.get(i, ("", 0))
                out[i] = (max(d, day), n + 1)
    return out


def callers_of(name, scripts_dir):
    """The tool files under scripts_dir that name `name` (tests and the file itself excluded)."""
    found = []
    stem = os.path.splitext(name)[0]
    for d, _, fs in os.walk(scripts_dir):
        if "__pycache__" in d or os.sep + "tests" in d or "nexus-description" in d:
            continue
        for f in fs:
            if not f.lower().endswith((".py", ".ps1", ".pyw")) or f == name:
                continue
            try:
                txt = read_text(os.path.join(d, f))
            except OSError:
                continue
            if name in txt or ("'%s'" % stem) in txt or ('"%s"' % stem) in txt:
                found.append(os.path.splitext(f)[0])
    return sorted(set(found))


def first_doc_line(path):
    txt = read_text(path)
    m = re.search(r'(?s)^(?:#![^\n]*\n)?\s*(?:[rRuU]?"""|<#)\s*(.+?)(?:\n\s*\n|"""|#>)', txt)
    if m:
        line = " ".join(m.group(1).split())
    else:
        line = next((l.lstrip("# ").strip() for l in txt.splitlines() if l.strip().startswith("#")), "")
    return line[:180]


def esc(s):
    return str(s).replace("|", "\\|").replace("\n", " ")


def build(rules_path, events_path, scripts_dir):
    rules = json.loads(read_text(rules_path)).get("rules", [])
    fired = last_fired(events_path)
    today = datetime.date.today().isoformat()
    lines = ["# Gate catalogue (GENERATED by gate-catalogue.py - do not edit by hand)",
             "<!-- GENERATED %s from %d gate-rules rows -->" % (today, len(rules)), ""]
    lines += ["Every gate in one place: the stage each runs at, what calls it, and the last day it refused something "
              "(from the event log). Pipeline assessment item 11 (2026-10-27): the gates sat mostly at finalize while "
              "the damage happened at package, install, test and brief time - the candidates below are the rows to "
              "move earlier or retire.", ""]
    never, finalize_only, rows_md = [], [], []
    for r in sorted(rules, key=lambda r: r.get("id", "")):
        rid, kind = r.get("id", "?"), r.get("kind", "?")
        if r.get("retired"):
            continue
        stage = "finalize only (needs the distro / page / previous release)" if FINALIZE_ONLY_KINDS.match(kind) \
            else "package + finalize"
        d, n = fired.get(rid, ("", 0))
        if not n:
            never.append(rid)
        if stage.startswith("finalize"):
            finalize_only.append(rid)
        scope = ", ".join(r.get("mods") or []) or ", ".join(r.get("kinds") or []) or "every mod"
        rows_md.append("| `%s` | %s | %s | %s | %s | %s |" % (rid, kind, stage, esc(scope)[:60],
                                                             d or "never", n or ""))
    lines += ["## Package gate rows (`gate-rules.json`, run by package-gate.ps1: %s)" % PACKAGE_GATE_CALLERS, "",
              "| Row | Kind | Runs at | Scope | Last fired | Times |", "|---|---|---|---|---|---|"] + rows_md + [""]
    by_row = {}                                      # a gate script a gate-rules row runs (package-script-passes, ...)
    for r in rules:
        if r.get("script") and not r.get("retired"):
            by_row.setdefault(os.path.basename(r["script"].replace("\\", "/")), []).append(r.get("id", "?"))
    gates_dir = os.path.join(scripts_dir, "gates")
    lines += ["## Standalone gate scripts (`scripts\\gates\\`)", "", "| Gate | What it refuses | Called by |",
              "|---|---|---|"]
    for f in sorted(os.listdir(gates_dir)) if os.path.isdir(gates_dir) else []:
        if not f.lower().endswith((".py", ".ps1")):
            continue
        calls = callers_of(f, scripts_dir) + ["package-gate row `%s`" % i for i in by_row.get(f, [])]
        lines.append("| `%s` | %s | %s |" % (f, esc(first_doc_line(os.path.join(gates_dir, f))),
                                             ", ".join(calls) or "(no tool names it)"))
    lines += ["", "## Candidates to move earlier or retire", "",
              "- **Never fired** (%d): %s" % (len(never), ", ".join("`%s`" % i for i in never) or "none"),
              "- **Finalize only** (%d): %s" % (len(finalize_only), ", ".join("`%s`" % i for i in finalize_only) or "none"),
              ""]
    return "\n".join(lines)


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--build", action="store_true")
    g.add_argument("--check", action="store_true")
    ap.add_argument("--rules", default=os.path.join(HERE, "gate-rules.json"))
    ap.add_argument("--events", default=os.path.join(MD, "pipeline-events.jsonl"))
    ap.add_argument("--scripts", default=HERE)
    ap.add_argument("--out")
    a = ap.parse_args(argv)
    out = a.out or os.path.join(os.path.dirname(os.path.abspath(a.rules)), "GATE-CATALOGUE.md")
    page = build(a.rules, a.events, a.scripts)
    if a.build:
        with io.open(out, "w", encoding="utf-8", newline="\n") as f:
            f.write(page + "\n")
        print("BUILT %s" % out)
        return 0
    if not os.path.isfile(out):
        print("NO CATALOGUE %s - run --build" % out)
        return 1
    have = read_text(out).split("\n")[2:]
    want = (page + "\n").split("\n")[2:]
    if have != want:
        print("STALE %s - run --build" % out)
        return 1
    print("OK %s" % out)
    return 0


if __name__ == "__main__":
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except Exception:                                  # noqa: BLE001
        pass
    sys.exit(main(sys.argv[1:]))
